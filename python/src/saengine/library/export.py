"""Generate the workbench's copy of the library schemas and defaults.

The Pydantic models are the single source of truth. The workbench needs their JSON Schemas
(for validation and completion in the JSON editor) and the default file contents (to create
a project without Python), so this writes them to a TypeScript module:

    python -m saengine.library.export <path/to/projectLibraries.generated.ts>

``tests/test_library.py`` fails when the checked-in file is out of date.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from saengine.library.bim import BuildingModel
from saengine.library.defaults import (
    default_building_model,
    default_floor_plan,
    default_material_library,
    default_object_library,
)
from saengine.library.floorplan import FloorPlan
from saengine.library.materials import MaterialLibrary
from saengine.library.objects import ObjectLibrary
from saengine.library.templates import TEMPLATES

HEADER = """/*---------------------------------------------------------------------------------------------
 *  Copyright (c) SAEngine contributors. All rights reserved.
 *  Licensed under the AGPL-3.0-only license. See LICENSE in the repository root for license information.
 *--------------------------------------------------------------------------------------------*/

// GENERATED by `python -m saengine.library.export` from the Pydantic models in
// python/src/saengine/library. Do not edit by hand.

import { IJSONSchema } from '../../../../base/common/jsonSchema.js';
"""

_IDENTIFIER = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _strip_openapi(value: Any) -> Any:
    """Drop Pydantic's OpenAPI ``discriminator`` hints; JSON Schema validators ignore them."""
    if isinstance(value, dict):
        return {k: _strip_openapi(v) for k, v in value.items() if k != "discriminator"}
    if isinstance(value, list):
        return [_strip_openapi(v) for v in value]
    return value


def json_schema(model: type[BaseModel], title: str) -> dict[str, Any]:
    schema = _strip_openapi(model.model_json_schema(by_alias=True, mode="validation"))
    schema["title"] = title
    return schema


def library_json(library: BaseModel) -> dict[str, Any]:
    return library.model_dump(mode="json", by_alias=True, exclude_none=True)


def _ts(value: Any, indent: int = 0) -> str:
    """A TypeScript literal with single-quoted strings (double quotes mean UI text in the workbench)."""
    pad = "\t" * indent
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = []
        for key, item in value.items():
            name = key if _IDENTIFIER.match(key) else _ts(key)
            items.append(f"{pad}\t{name}: {_ts(item, indent + 1)},")
        return "{\n" + "\n".join(items) + f"\n{pad}}}"
    if isinstance(value, list):
        if not value:
            return "[]"
        if all(not isinstance(v, dict | list) for v in value):
            return "[" + ", ".join(_ts(v) for v in value) + "]"
        return "[\n" + "\n".join(f"{pad}\t{_ts(v, indent + 1)}," for v in value) + f"\n{pad}]"
    if isinstance(value, str):
        return (
            "'"
            + json.dumps(value, ensure_ascii=False)[1:-1].replace('\\"', '"').replace("'", "\\'")
            + "'"
        )
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    return json.dumps(value)


def generate_typescript() -> str:
    exports = [
        ("MATERIALS_SCHEMA", "IJSONSchema", json_schema(MaterialLibrary, "SAEngine materials")),
        ("OBJECTS_SCHEMA", "IJSONSchema", json_schema(ObjectLibrary, "SAEngine object types")),
        ("DEFAULT_MATERIALS", "object", library_json(default_material_library())),
        ("DEFAULT_OBJECTS", "object", library_json(default_object_library())),
        ("FLOOR_PLAN_SCHEMA", "IJSONSchema", json_schema(FloorPlan, "SAEngine floor plan")),
        ("DEFAULT_FLOOR_PLAN", "object", library_json(default_floor_plan())),
        ("BIM_SCHEMA", "IJSONSchema", json_schema(BuildingModel, "SAEngine building model")),
        ("DEFAULT_BIM", "object", library_json(default_building_model())),
        ("TEMPLATES", "{ readonly [defName: string]: object }", TEMPLATES),
    ]
    body = "\n".join(
        f"export const {name}: {type_} = {_ts(value)};\n" for name, type_, value in exports
    )
    return HEADER + "\n" + body


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    Path(args[0]).write_text(generate_typescript(), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
