/** Puts a command's description where the library looks for it, in every loaded language that lacks one. */
export function registerCommandDescription(group: string, name: string, description?: string): void {
	const text = description ?? COMMAND_DESCRIPTIONS[name.toUpperCase()];
	if (!text) {
		return;
	}
	const messages = (AcApI18n as unknown as { _messages?: Record<string, Record<string, unknown>> })._messages;
	if (!messages) {
		return;
	}
	for (const locale of Object.keys(messages)) {
		const root = messages[locale] as Record<string, Record<string, Record<string, { description?: string }>>>;
		const command = root.command ??= {};
		const byGroup = command[group] ??= {};
		const entry = byGroup[name.toLowerCase()] ??= {};
		entry.description ??= text;
	}
}
