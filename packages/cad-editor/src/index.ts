import { AcApDocManager, AcApOpenViewMode, AcApSettingManager, AcApXrefManager, AcEdOpenMode, MTEXT_RENDERER_WORKER_FILE } from '@mlightcad/cad-simple-viewer';
import { applyGenerated, CadGeneratedDrawing, CadPoint } from './generated.js';

export type { CadEntitySpec, CadGeneratedDrawing, CadLayerSpec, CadPoint } from './generated.js';
export { setTrustedTypesHost, type TrustedTypesHost } from './trustedTypes.js';

export interface CadEditorOptions {
	readonly container: HTMLElement;
	/** Folder URL (with trailing slash) holding the bundled worker script. */
	readonly workerBaseUrl: string;
	/** Folder URL (with trailing slash) holding `fonts/` and `templates/`. */
	readonly assetBaseUrl: string;
	/** mlightcad's own controls to show (default: both). */
	readonly chrome?: CadChrome;
	/** Canvas background as 0xRRGGBB (default: black). ACI 7 linework turns black on light ones. */
	readonly background?: number;
}

/** mlightcad's own controls over the canvas. */
export interface CadChrome {
	/** The AutoCAD-style command line ("Type command"). */
	readonly commandLine?: boolean;
	/** The floating undo / redo / erase toolbar. */
	readonly shortcutToolbar?: boolean;
}

/** A reference drawing shown read-only and greyed under the content (e.g. an architect's plan). */
export interface CadUnderlay {
	/** Display name, e.g. the file name. */
	readonly name: string;
	/** DXF text. */
	readonly dxf: string;
	/** Where the drawing's origin goes, in drawing units. */
	readonly offset?: CadPoint;
	/** Scale from the underlay's units to the drawing's. */
	readonly scale?: number;
	/** Rotation about its origin, in degrees. */
	readonly rotation?: number;
}

export interface CadEditor {
	/** Opens DXF text as the drawing; `name` is its title. */
	openDxf(name: string, dxf: string): Promise<boolean>;
	/**
	 * Starts an empty metric drawing from the bundled template. A read-only drawing offers
	 * viewing commands only; its content comes from {@link setGenerated}.
	 */
	newDrawing(options?: { readonly readOnly?: boolean }): Promise<boolean>;
	/**
	 * Replaces the content generated by the host (e.g. from a building model) with `drawing`.
	 * Generated entities sit on locked layers, cannot be selected and are not undoable edits.
	 */
	setGenerated(drawing: CadGeneratedDrawing): void;
	/**
	 * Replaces the transient preview (snap markers, rubber bands, ...) drawn over the generated
	 * content; like it, the preview cannot be selected or undone.
	 */
	setPreview(drawing: CadGeneratedDrawing): void;
	/** The drawing point under a mouse position (client coordinates). */
	toWorld(clientX: number, clientY: number): CadPoint;
	/** Drawing units per screen pixel at the current zoom, e.g. for pick tolerances. */
	unitsPerPixel(): number;
	/** Shows `underlay` under the drawing, replacing the previous one; `undefined` removes it. */
	setUnderlay(underlay: CadUnderlay | undefined): Promise<void>;
	/** Fits the whole drawing in the view. */
	zoomExtents(): void;
	/** The drawing as DXF text (AutoCAD 2018 format). */
	toDxf(): string;
	/** Runs an AutoCAD-style command, e.g. "line" or "dimlinear". */
	execute(command: string): Promise<void>;
	/** Sets the canvas background (0xRRGGBB); ACI 7 linework follows it (black on light, white on dark). */
	setBackground(rgb: number): void;
	/** Shows or hides mlightcad's own controls (fields left out stay as they are). */
	setChrome(chrome: CadChrome): void;
	/** Which of mlightcad's own controls show now. */
	getChrome(): Required<CadChrome>;
	/** Called when a control is shown or hidden, also by its own close button; returns an unsubscribe function. */
	onDidChangeChrome(listener: () => void): () => void;
	/** Moves the keyboard focus to the command line, when it shows. */
	focusCommandLine(): void;
	/** Called when the user changes the open drawing (an undoable edit); returns an unsubscribe function. */
	onDidChange(listener: () => void): () => void;
	dispose(): Promise<void>;
}

/**
 * The mlightcad editor in `container`. mlightcad keeps one document manager per page, so only
 * one CAD editor can be live at a time.
 */
export function createCadEditor(options: CadEditorOptions): CadEditor {
	const manager = AcApDocManager.createInstance({
		container: options.container,
		autoResize: true,
		baseUrl: options.assetBaseUrl,
		webworkerFileUrls: { mtextRender: options.workerBaseUrl + MTEXT_RENDERER_WORKER_FILE },
	});
	if (!manager) {
		throw new Error('A CAD editor is already open; close it first.');
	}

	// mlightcad keeps its controls' visibility in one setting store per page; there is one live
	// editor at a time, so each editor sets what it wants when it starts.
	const settings = AcApSettingManager.instance;
	const CHROME_KEYS = { commandLine: 'isShowCommandLine', shortcutToolbar: 'isShowShortCutToolbar' } as const;
	const setChrome = (chrome: CadChrome) => {
		for (const [field, key] of Object.entries(CHROME_KEYS) as [keyof CadChrome, typeof CHROME_KEYS[keyof CadChrome]][]) {
			const value = chrome[field];
			if (value !== undefined && settings.get(key) !== value) {
				settings.set(key, value);
			}
		}
	};
	setChrome({ commandLine: true, shortcutToolbar: true, ...options.chrome });
	const chromeListeners = new Set<() => void>();
	const onSettingChanged = (args: { key: string }) => {
		if (Object.values<string>(CHROME_KEYS).includes(args.key)) {
			chromeListeners.forEach(listener => listener());
		}
	};
	settings.events.modified.addEventListener(onSettingChanged);

	let background = options.background;
	const applyBackground = () => {
		if (background !== undefined && manager.curView.backgroundColor !== background) {
			manager.curView.backgroundColor = background;
		}
	};
	applyBackground();

	const listeners = new Set<() => void>();
	let generated = new Set<string>();
	let preview = new Set<string>();
	let underlaySession: string | undefined;
	let underlayVersion = 0;
	// mlightcad also reports loading and its own housekeeping as database events; a user's edit
	// is what lands on the undo stack (every command runs in an undoable transaction).
	let checkQueued = false;
	const fire = () => {
		if (checkQueued) {
			return;
		}
		checkQueued = true;
		queueMicrotask(() => {
			checkQueued = false;
			const transactions = manager.curDocument.database.transactionManager;
			if (transactions.canUndo() || transactions.canRedo()) {
				listeners.forEach(listener => listener());
			}
		});
	};
	// Generated entities belong to the host's model: keep them out of every selection, so no
	// command can move or erase them.
	const deselectGenerated = ({ ids }: { ids: string[] }) => {
		const owned = ids.filter(id => generated.has(id) || preview.has(id));
		if (owned.length) {
			manager.curView.selectionSet.delete(owned);
		}
	};
	let unsubscribeDocument: (() => void) | undefined;
	const watchDocument = () => {
		unsubscribeDocument?.();
		const events = manager.curDocument.database.events;
		const managers = [events.entityAppended, events.entityModified, events.entityErased, events.layerAppended, events.layerModified, events.layerErased];
		managers.forEach(m => m.addEventListener(fire));
		const selection = manager.curView.selectionSet;
		selection.events.selectionAdded.addEventListener(deselectGenerated);
		unsubscribeDocument = () => {
			managers.forEach(m => m.removeEventListener(fire));
			selection.events.selectionAdded.removeEventListener(deselectGenerated);
		};
	};
	const opened = (ok: boolean) => {
		if (ok) {
			generated = new Set();
			preview = new Set();
			watchDocument();
			// Opening a drawing applies its own background (MODELBKCOLOR); the host's wins.
			applyBackground();
		}
		return ok;
	};

	const encoder = new TextEncoder();
	// Fit the whole drawing on open; plans generated by tools often carry no saved view.
	const open = async (name: string, dxf: string, mode: AcEdOpenMode) =>
		opened(await manager.openDocument(name, encoder.encode(dxf).buffer as ArrayBuffer, { mode, openViewMode: AcApOpenViewMode.Extents }));

	return {
		openDxf: (name, dxf) => open(name, dxf, AcEdOpenMode.Write),
		newDrawing: async drawingOptions => {
			if (!drawingOptions?.readOnly) {
				return opened(await manager.newDocument({ mode: AcEdOpenMode.Write }));
			}
			// mlightcad's newDocument always opens for writing; open the template directly instead.
			const template = await fetch(`${options.assetBaseUrl}templates/acadiso.dxf`);
			return template.ok && open('', await template.text(), AcEdOpenMode.Read);
		},
		setGenerated: drawing => {
			generated = applyGenerated(manager.curDocument.database, generated, drawing);
		},
		setUnderlay: async underlay => {
			const version = ++underlayVersion;
			const xrefs = AcApXrefManager.instance;
			if (underlaySession) {
				xrefs.unload(underlaySession);
				underlaySession = undefined;
			}
			if (!underlay) {
				return;
			}
			const session = await xrefs.attachOverlay({
				blockName: 'SAENGINE-UNDERLAY',
				fileName: `${underlay.name.replace(/\.dxf$/i, '')}.dxf`,
				sourcePath: underlay.name,
				content: encoder.encode(underlay.dxf).buffer as ArrayBuffer,
				transform: {
					position: { x: underlay.offset?.[0] ?? 0, y: underlay.offset?.[1] ?? 0, z: 0 },
					scale: underlay.scale ?? 1,
					rotationRad: (underlay.rotation ?? 0) * Math.PI / 180,
				},
			});
			if (version !== underlayVersion) {
				xrefs.unload(session.id); // replaced while it was loading
				return;
			}
			underlaySession = session.id;
			// Reference drawings read best greyed out, behind the host's own linework.
			manager.setOverlayCompareDisplay(session.overlayId, { enabled: true, baseColor: 0x6b7280 });
		},
		setPreview: drawing => {
			preview = applyGenerated(manager.curDocument.database, preview, drawing);
		},
		toWorld: (clientX, clientY) => {
			const view = manager.curView;
			const rect = view.canvas.getBoundingClientRect();
			const point = view.screenToWorld({ x: clientX - rect.left, y: clientY - rect.top });
			return [point.x, point.y];
		},
		unitsPerPixel: () => {
			const view = manager.curView;
			const a = view.screenToWorld({ x: 0, y: 0 });
			const b = view.screenToWorld({ x: 100, y: 0 });
			return Math.hypot(b.x - a.x, b.y - a.y) / 100;
		},
		zoomExtents: () => manager.curView.zoomToFitDrawing(),
		toDxf: () => {
			const out = manager.curDocument.database.dxfOut(undefined, 6);
			return typeof out === 'string' ? out : new TextDecoder().decode(out);
		},
		execute: command => manager.executeCommandString(command),
		setBackground: rgb => {
			background = rgb & 0xffffff;
			applyBackground();
		},
		setChrome,
		getChrome: () => ({ commandLine: !!settings.get(CHROME_KEYS.commandLine), shortcutToolbar: !!settings.get(CHROME_KEYS.shortcutToolbar) }),
		onDidChangeChrome: listener => {
			chromeListeners.add(listener);
			return () => chromeListeners.delete(listener);
		},
		focusCommandLine: () => options.container.querySelector<HTMLInputElement>('input.ml-cli-text')?.focus(),
		onDidChange: listener => {
			listeners.add(listener);
			return () => listeners.delete(listener);
		},
		dispose: async () => {
			unsubscribeDocument?.();
			if (underlaySession) {
				AcApXrefManager.instance.unload(underlaySession);
			}
			listeners.clear();
			chromeListeners.clear();
			settings.events.modified.removeEventListener(onSettingChanged);
			await manager.destroy();
		},
	};
}
