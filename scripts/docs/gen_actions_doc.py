"""Generate docs/actions.md: the catalogue of shared editing actions (saengine.actions).

Each action with its kind, the parts it reads or edits, its parameters (from the Pydantic model's
JSON Schema) and an example. Run it after changing an action; ``tests/test_actions.py`` fails
when the committed catalogue is out of date::

    python -I scripts/docs/gen_actions_doc.py          # write docs/actions.md
    python -I scripts/docs/gen_actions_doc.py --check  # exit 1 when it is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "python" / "src"
OUT = ROOT / "docs" / "actions.md"

#: The sections of the catalogue, by the first word of the action's name.
SECTIONS = [
    (
        "Query",
        (
            "project.summary",
            "members.list",
            "results.summary",
            "checks.list",
            "actions.help",
        ),
    ),
    ("Project", ("project.create", "building.generate")),
    ("Settings", ("settings.",)),
    ("Soil", ("soil.",)),
    ("Grid and storeys", ("grid.", "storeys.", "storey.")),
    ("Materials and object types", ("material.", "type.")),
    ("Members", ("columns.", "beams.", "slabs.", "walls.", "member.", "members.")),
    ("Loads", ("load.",)),
    ("Foundations", ("foundations.", "footing.")),
    ("Run and export", ("run.", "design.", "export.")),
]

INTRO = """# Shared editing actions

<!-- Generated by scripts/docs/gen_actions_doc.py: do not edit by hand. -->

One catalogue of typed, validated edits of a SAEngine project, used by every surface: the command
line (`saengine action`, [docs/cli.md](cli.md#shared-editing-actions)), the SDK
(`saengine.api.list_actions` and `run_actions`, [docs/sdk](sdk/README.md)), the JSON-RPC
methods `actions/list` and `actions/run`, the app and its assistant. With it a script or the
assistant builds a whole project from an empty folder to the report.

- **A batch is all or nothing.** The steps run in order on one view of the project (a later step
  sees what an earlier one changed); when a step is refused, no change is returned or written.
- **Every value is checked** by the parameters' model, by the input guardrails (the same rules as
  the editors: `python/src/saengine/library/data/guardrails.json`, the code pack's limits) and by
  the part models: a changed part must still validate. Only what the step made worse counts; a
  problem the file had before stays the engineer's to fix. A refusal names the field, the value
  and the reason.
- **Kinds.** `edit` actions change part files only (the app applies the changes as one undo
  step); `run` actions work on the saved project (the app saves first; with `write` the edits
  before a run step are written first, and stay written if a later step fails); `query` actions
  read only.
- **Ids** are made as the floor plan editor makes them: the group's letter and the lowest free
  number (C1, B1, W1, S1, F1), LL1 and PL1 for line and point loads, BH-1 for boreholes.
- **Code independence.** No action branches on the code pack: the pack in force (the project's)
  gives the values (live loads, Ec, Es, wall weights, limits).
- Grid points are written `"A-1"` (X line, Y line) or `{"x": "A", "y": "1", "dx": 0, "dy": 0}`;
  lengths are in mm, loads in kN/m² (area), kN/m (line) and kN (point), stresses in MPa.

## Building a project from scratch

The order the assistant follows (`actions.help` returns it too):

"""


def _type(prop: dict[str, Any], defs: dict[str, Any]) -> str:
    if "$ref" in prop:
        return prop["$ref"].rsplit("/", 1)[-1]
    if "enum" in prop:
        return " or ".join(json.dumps(v) for v in prop["enum"])
    if "const" in prop:
        return json.dumps(prop["const"])
    if "anyOf" in prop:
        parts = [_type(p, defs) for p in prop["anyOf"]]
        return " or ".join(p for p in parts if p != "null") + (
            " or null" if "null" in parts else ""
        )
    kind = prop.get("type", "any")
    if kind == "array":
        return f"list of {_type(prop.get('items') or {}, defs)}"
    if kind == "object":
        return "object"
    return str(kind)


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def action_section(info: Any) -> str:
    schema = info.params_schema
    defs = schema.get("$defs") or {}
    required = set(schema.get("required") or [])
    lines = [
        f"### `{info.name}`",
        "",
        f"{info.summary}",
        "",
        f"Kind: **{info.kind}**. Parts: {', '.join(f'`{p}`' for p in info.parts) or '-'}.",
        "",
    ]
    props = schema.get("properties") or {}
    if props:
        lines += [
            "| Parameter | Type | Default | Description |",
            "| --- | --- | --- | --- |",
        ]
        for name, prop in props.items():
            default = "required" if name in required else json.dumps(prop.get("default"))
            lines.append(
                f"| `{name}` | {_cell(_type(prop, defs))} | {_cell(default)} | "
                f"{_cell(prop.get('description') or '')} |"
            )
        lines.append("")
    else:
        lines += ["No parameters.", ""]
    if info.example is not None:
        step = {"action": info.name, "params": info.example}
        lines += ["```json", json.dumps(step, ensure_ascii=False), "```", ""]
    return "\n".join(lines)


def _section_of(name: str) -> str:
    for title, prefixes in SECTIONS:
        if any(name == p or (p.endswith(".") and name.startswith(p)) for p in prefixes):
            return title
    return "Other"


def generate() -> str:
    sys.path.insert(0, str(SRC))
    from saengine.actions import list_actions
    from saengine.actions.catalogue.query import PLAYBOOK

    infos = list_actions()
    out = [INTRO]
    out += [f"{i}. {step}" for i, step in enumerate(PLAYBOOK, 1)]
    out += [
        "",
        (
            'A batch file is a list of steps (or `{"steps": [...]}`); '
            "`python/tests/data/actions/three-storey-rc.json` builds, runs and designs a "
            "three-storey RC frame."
        ),
        "",
        "## Catalogue",
        "",
    ]
    titles = [t for t, _ in SECTIONS] + ["Other"]
    grouped: dict[str, list[Any]] = {t: [] for t in titles}
    for info in infos:
        grouped[_section_of(info.name)].append(info)
    for title in titles:
        if grouped[title]:
            out.append(
                f"- [{title}](#{title.lower().replace(' ', '-')}): "
                + ", ".join(f"`{i.name}`" for i in grouped[title])
            )
    out.append("")
    for title in titles:
        if not grouped[title]:
            continue
        out += [f"## {title}", ""]
        out += [action_section(info) for info in grouped[title]]
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when out of date")
    args = parser.parse_args(argv)
    text = generate()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print(f"{OUT} is out of date: run python -I scripts/docs/gen_actions_doc.py")
            return 1
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"{OUT}: {len(text.splitlines())} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
