"""Generate docs/sdk/reference.md: the versioned Python API and the JSON-RPC methods.

The Python API is ``saengine.api`` (its ``__all__``, with each name's signature and the first
paragraph of its docstring). The JSON-RPC methods are read from ``saengine/rpc/server.py`` without
starting it: every ``@server.feature("<method>")`` with the parameters its body reads
(``args["x"]``, ``args.get("x")``), whether it runs in a worker thread, and the docstring of the
handler it calls. Run it after changing either; CI's test (``tests/test_sdk.py``) fails when the
committed reference is out of date::

    python -I scripts/docs/gen_sdk_reference.py          # write docs/sdk/reference.md
    python -I scripts/docs/gen_sdk_reference.py --check  # exit 1 when it is out of date
"""

from __future__ import annotations

import argparse
import ast
import inspect
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "python" / "src"
OUT = ROOT / "docs" / "sdk" / "reference.md"


def _first_paragraph(doc: str | None) -> str:
    text = inspect.cleandoc(doc or "").split("\n\n", 1)[0]
    return " ".join(text.split())


def _handler_docs(path: Path) -> dict[str, str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    return {
        node.name: _first_paragraph(ast.get_docstring(node))
        for node in tree.body
        if isinstance(node, ast.FunctionDef)
    }


def rpc_methods(server: Path, handlers: Path) -> list[dict]:
    """Every JSON-RPC method of the server, sorted by name."""
    docs = _handler_docs(handlers)
    tree = ast.parse(server.read_text(encoding="utf-8"))
    methods = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.FunctionDef):
            continue
        name, worker = None, False
        for deco in node.decorator_list:
            if (
                isinstance(deco, ast.Call)
                and isinstance(deco.func, ast.Attribute)
                and deco.func.attr == "feature"
                and deco.args
                and isinstance(deco.args[0], ast.Constant)
            ):
                name = deco.args[0].value
            elif isinstance(deco, ast.Name) and deco.id.endswith("worker"):
                worker = True
        if not isinstance(name, str) or "/" not in name:
            continue
        params: dict[str, bool] = {}
        handler = None
        for sub in ast.walk(node):
            if (
                isinstance(sub, ast.Subscript)
                and isinstance(sub.slice, ast.Constant)
                and isinstance(sub.slice.value, str)
                and isinstance(sub.value, ast.Name)
                and sub.value.id == "args"
            ):
                params.setdefault(sub.slice.value, True)
            elif isinstance(sub, ast.Call) and isinstance(sub.func, ast.Attribute):
                if (
                    sub.func.attr == "get"
                    and isinstance(sub.func.value, ast.Name)
                    and sub.func.value.id == "args"
                    and sub.args
                    and isinstance(sub.args[0], ast.Constant)
                ):
                    params.setdefault(sub.args[0].value, False)
                elif isinstance(sub.func.value, ast.Name) and sub.func.value.id == "handlers":
                    handler = handler or sub.func.attr
        methods.append(
            {
                "name": name,
                "params": params,
                "worker": worker,
                "handler": handler,
                "doc": docs.get(handler or "", ""),
            }
        )
    return sorted(methods, key=lambda m: m["name"])


def python_api() -> tuple[str, list[dict]]:
    sys.path.insert(0, str(SRC))
    from saengine import api

    entries = []
    for name, (module, attr) in sorted(api.exports().items()):
        value = getattr(api, name)
        try:
            signature = str(inspect.signature(value))
        except (TypeError, ValueError):
            signature = ""
        kind = "class" if inspect.isclass(value) else "function"
        entries.append(
            {
                "name": name,
                "kind": kind,
                "signature": signature if kind == "function" else "",
                "where": f"{module}.{attr}",
                "doc": _first_paragraph(inspect.getdoc(value)),
            }
        )
    return api.API_VERSION, entries


def render(version: str, entries: list[dict], methods: list[dict]) -> str:
    lines = [
        "# SAEngine SDK reference",
        "",
        "<!-- Generated by scripts/docs/gen_sdk_reference.py: do not edit by hand. -->",
        "",
        (
            f"Python API version **{version}** (`saengine.api.API_VERSION`). The guide, the versioning"
            " rules and examples are in [README.md](README.md)."
        ),
        "",
        "## Python API (`saengine.api`)",
        "",
    ]
    for e in entries:
        head = (
            f"### `{e['name']}{e['signature']}`"
            if e["kind"] == "function"
            else (f"### class `{e['name']}`")
        )
        lines += [head, "", f"`{e['where']}`" + (f": {e['doc']}" if e["doc"] else ""), ""]
    lines += [
        "## JSON-RPC methods",
        "",
        (
            "`python -m saengine.rpc.server` speaks JSON-RPC 2.0 over stdio with LSP framing"
            " (`Content-Length` headers). Parameters in **bold** are required; *worker* methods run"
            " in a worker thread, so long calls do not block the others."
        ),
        "",
        "| Method | Parameters | Handler | What it does |",
        "| --- | --- | --- | --- |",
    ]
    for m in methods:
        params = ", ".join(f"**{k}**" if req else k for k, req in m["params"].items()) or "—"
        handler = f"`{m['handler']}`" + (" (worker)" if m["worker"] else "") if m["handler"] else ""
        doc = m["doc"].replace("|", "\\|")
        lines.append(f"| `{m['name']}` | {params} | {handler} | {doc} |")
    lines.append("")
    return "\n".join(lines)


def generate() -> str:
    version, entries = python_api()
    methods = rpc_methods(SRC / "saengine/rpc/server.py", SRC / "saengine/rpc/handlers.py")
    return render(version, entries, methods)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when out of date")
    args = parser.parse_args(argv)
    text = generate()
    current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
    if args.check:
        if current != text:
            print(f"{OUT} is out of date: run scripts/docs/gen_sdk_reference.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT}: {text.count(chr(10))} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
