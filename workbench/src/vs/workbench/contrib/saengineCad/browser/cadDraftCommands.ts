export interface ICadDraftCommandSpec {
	/** Workbench command ID (`saengine.cad.<cmd>`). */
	readonly id: string;
	/** Command string executed on the active CAD editor (`editor.execute(...)`). */
	readonly cadCommand: string;
	/** Canonical uppercase command name matching `packages/cad-editor/COMMANDS.md`. */
	readonly canonicalName: string;
	/** AutoCAD-style display title. */
	readonly title: ILocalizedString;
	/** Tooltip including the command word. */
	readonly tooltip: ILocalizedString;
	readonly icon: ThemeIcon;
	readonly menuId: MenuId;
	readonly group: string;
	readonly order: number;
	readonly size?: RibbonButtonSize;
}

